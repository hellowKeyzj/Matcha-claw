use std::path::PathBuf;

use crate::{
    ActivityExecutionOutcome, NativeRunSettled, application::team_runtime::TeamRuntimeStatus,
};

use organization::{
    ActivityClaim, ActivityId, BeginCancellationOutcome, CreateGraphRunOutcome, DeliveryId,
    GraphDefinition, GraphRunId, IdempotencyKey, RunCommand, StoreFault, TeamDecisionCommand,
    TeamDecisionReceipt, TeamId, TeamNodeEvent, TeamNodeEventOutcome, TeamTriggerFireOutcome,
    TombstoneOutcome, TriggerFireRequest,
    package::{TeamSkillSelectionError, TeamSkillSelectionId},
    run::{
        approval::{HumanDecisionCommand, HumanDecisionOutcome},
        event::OpaqueId,
    },
};

use super::team_run::{
    ManualTeamCreateOutcome, TeamDeleteOutcome, TeamMaterializationCommandOutcome,
    TeamNodeTerminalResolution, TeamNodeTerminalResult, TeamRunActivityError,
    TeamRunActivityOutcome, TeamRunActivityStart, TeamRunCommandOutcome, TeamRunTriggerOutcome,
};

pub(crate) enum OrganizationCommand {
    SaveTeamPrompts {
        expected_revision: u64,
        values: std::collections::BTreeMap<String, String>,
        reply: crate::call::CallReply<Result<crate::prompts::TeamPromptSettings, crate::TeamPromptSettingsError>>,
    },
    NativeOperationSettled {
        key: super::actor::OrganizationLaneKey,
    },
    RunNativeLease {
        run_id: GraphRunId,
        reply: tokio::sync::oneshot::Sender<Option<std::sync::Arc<tokio::sync::OwnedRwLockReadGuard<()>>>>,
    },
    TeamSkillAuthorize {
        package_root: PathBuf,
        reply: crate::call::CallReply<Result<TeamSkillSelectionId, TeamSkillSelectionError>>,
    },
    TeamSkillMaterialize {
        selection_id: TeamSkillSelectionId,
        endpoint: organization::RuntimeEndpointReference,
        source_agent: Option<organization::ManagedAgentReference>,
        team_id: TeamId,
        idempotency_key: IdempotencyKey,
        reply: crate::call::CallReply<TeamMaterializationCommandOutcome>,
    },
    ManualTeamMaterialize {
        team_id: TeamId,
        team_name: String,
        roles: Vec<organization::ManualTeamRoleBinding>,
        idempotency_key: IdempotencyKey,
        reply: crate::call::CallReply<TeamMaterializationCommandOutcome>,
    },
    ManualTeamCreate {
        team_id: TeamId,
        team_name: String,
        roles: Vec<organization::ManualTeamRoleBinding>,
        materialization_idempotency_key: IdempotencyKey,
        run: organization::GraphRunFacts,
        run_idempotency_key: String,
        reply: crate::call::CallReply<ManualTeamCreateOutcome>,
        continue_run: tokio::sync::oneshot::Sender<(TeamId, organization::GraphRunFacts, String, crate::call::CallReply<ManualTeamCreateOutcome>)>,
    },
    ManualTeamRunCreate {
        native_slot: tokio::sync::OwnedSemaphorePermit,
        team_id: TeamId,
        run: organization::GraphRunFacts,
        run_idempotency_key: String,
        reply: crate::call::CallReply<ManualTeamCreateOutcome>,
    },
    TeamDelete {
        team_id: TeamId,
        idempotency_key: IdempotencyKey,
        observed_at: u64,
        reply: crate::call::CallReply<Result<TeamDeleteOutcome, StoreFault>>,
        guard: tokio::sync::OwnedRwLockWriteGuard<()>,
        slot: tokio::sync::OwnedSemaphorePermit,
    },
    TeamDeleteRunNativeSettled {
        team_id: TeamId,
        run_id: GraphRunId,
        idempotency_key: String,
        native: organization::NativeDeletionEvidence,
        observed_at: u64,
        cancellation: tokio_util::sync::CancellationToken,
    },
    TeamDeleteUnconfirmedRunSettled {
        team_id: TeamId,
        run_id: GraphRunId,
        idempotency_key: String,
        outcome: crate::ports::native_effects::RoleSessionRetirementOutcome,
        observed_at: u64,
        cancellation: tokio_util::sync::CancellationToken,
    },
    TeamDeleteRemovalSettled {
        team_id: TeamId,
        endpoint: organization::RuntimeEndpointReference,
        outcome: organization::MaterializationOperationOutcome,
    },
    RunCreate {
        team_id: TeamId,
        run_id: GraphRunId,
        idempotency_key: String,
        workflow_plan: organization::WorkflowPlan,
        source_identity: String,
        template_revision: u64,
        created_at: u64,
        reply: crate::call::CallReply<Result<CreateGraphRunOutcome, StoreFault>>,
    },
    RoleSessionCreate {
        native_slot: tokio::sync::OwnedSemaphorePermit,
        team_id: TeamId,
        run_id: GraphRunId,
        role_id: crate::RoleId,
        idempotency_key: IdempotencyKey,
        scope: crate::application::team_runtime::RoleSessionCreateScope,
        reply: crate::call::CallReply<Result<crate::RoleSessionReceipt, crate::application::team_runtime::RoleSessionCreateError>>,
    },
    RunCreateFromTeamTemplate {
        native_slot: tokio::sync::OwnedSemaphorePermit,
        team_id: TeamId,
        run_id: GraphRunId,
        idempotency_key: IdempotencyKey,
        created_at: u64,
        reply: crate::call::CallReply<(
            Result<CreateGraphRunOutcome, TeamRuntimeStatus>,
            Option<crate::TeamCreationFailure>,
            Option<crate::run::public_projection::TeamRunPublicWorkspace>,
        )>,
    },
    TaskCreate {
        native_slot: tokio::sync::OwnedSemaphorePermit,
        request: crate::task_execution::TaskExecutionRequest,
        reply: crate::call::CallReply<Result<String, crate::task_execution::TaskExecutionReceipt>>,
    },
    TaskNativeExecutionObserved {
        identity: crate::task_execution::TaskExecutionIdentity,
        request: crate::ActivityExecutionRequest,
        execution: crate::TaskNativeExecution,
        reply: tokio::sync::oneshot::Sender<Result<(), StoreFault>>,
    },
    TaskCancel {
        native_slot: tokio::sync::OwnedSemaphorePermit,
        identity: crate::task_execution::TaskExecutionIdentity,
        idempotency_key: IdempotencyKey,
        requested_at: u64,
        reply: crate::call::CallReply<crate::task_execution::TaskExecutionReceipt>,
    },
    RunCancel {
        native_slot: tokio::sync::OwnedSemaphorePermit,
        run_id: GraphRunId,
        idempotency_key: String,
        requested_at: u64,
        reply: crate::call::CallReply<Result<BeginCancellationOutcome, StoreFault>>,
    },
    RunDelete {
        run_id: GraphRunId,
        idempotency_key: String,
        tombstoned_at: u64,
        reply: crate::call::CallReply<Result<TombstoneOutcome, StoreFault>>,
    },
    RunDeleteAndPurge {
        native_slot: tokio::sync::OwnedSemaphorePermit,
        run_id: GraphRunId,
        idempotency_key: String,
        observed_at: u64,
        reply: crate::call::CallReply<Result<organization::GraphRunPurgeOutcome, StoreFault>>,
    },
    RunPurge {
        request: organization::TeamRunPurgeRequest,
        reply: crate::call::CallReply<Result<organization::GraphRunPurgeOutcome, StoreFault>>,
    },
    TriggerFire {
        request: TriggerFireRequest,
        fired_at: u64,
        reply: crate::call::CallReply<Result<TeamRunTriggerOutcome, StoreFault>>,
    },
    WebhookTriggerFire {
        webhook_path: String,
        idempotency_key: String,
        fired_at: u64,
        reply: crate::call::CallReply<Result<TeamTriggerFireOutcome, TeamRuntimeStatus>>,
    },
    GraphSave {
        command: RunCommand,
        definition: GraphDefinition,
        reply: crate::call::CallReply<Result<TeamRunCommandOutcome, StoreFault>>,
    },
    GraphPatch {
        patch: crate::application::team_runtime::TeamGraphPatchDraft,
        reply: crate::call::CallReply<Result<TeamRunCommandOutcome, StoreFault>>,
    },
    RecordEvidence {
        record: crate::run::evidence::EvidenceRecord,
        reply:
            tokio::sync::oneshot::Sender<Result<crate::run::evidence::RecordOutcome, StoreFault>>,
    },
    RunStart {
        team_id: TeamId,
        run_id: GraphRunId,
        epoch: Option<String>,
        version: String,
        reply: tokio::sync::oneshot::Sender<Result<bool, StoreFault>>,
    },
    RunReworkContinue {
        request: crate::ReworkContinueRequest,
        reply: tokio::sync::oneshot::Sender<Result<(), StoreFault>>,
    },
    RuntimeGraphPatch {
        scope: crate::TeamRunExecutionScope,
        patch: crate::store::RuntimePromptPatch,
        reply: tokio::sync::oneshot::Sender<Result<serde_json::Value, StoreFault>>,
    },
    Design {
        operation: crate::application::design::DesignOperation,
        resolver: std::sync::Arc<dyn crate::RoleSessionIdentityResolver>,
        reply: tokio::sync::oneshot::Sender<Result<(serde_json::Value, bool), StoreFault>>,
    },
    NodeEvent {
        command: RunCommand,
        event: TeamNodeEvent,
        reply: crate::call::CallReply<Result<TeamNodeEventOutcome, StoreFault>>,
    },
    NodeTerminalResolve {
        run_id: GraphRunId,
        node_execution_id: OpaqueId,
        event: String,
        terminal: Option<TeamNodeTerminalResolution>,
        summary: String,
        output_port: Option<String>,
        idempotency_key: String,
        resolved_at: u64,
        reply: crate::call::CallReply<Result<TeamNodeTerminalResult, StoreFault>>,
    },
    ApprovalResolve {
        command: HumanDecisionCommand,
        reply: crate::call::CallReply<Result<HumanDecisionOutcome, StoreFault>>,
    },
    DecisionSubmit {
        command: TeamDecisionCommand,
        reply: crate::call::CallReply<Result<TeamDecisionReceipt, StoreFault>>,
    },
    TaskBoardMutate {
        team_id: TeamId,
        run_id: GraphRunId,
        operation: crate::application::task_board::TaskBoardMutation,
        reply: crate::call::CallReply<Result<crate::application::task_board::MutationResult, crate::application::task_board::MutationError>>,
    },
    ScheduleReadyNodes {
        run_id: GraphRunId,
        now: u64,
        reply: tokio::sync::oneshot::Sender<(Result<Vec<ActivityId>, StoreFault>, bool)>,
    },
    ClaimActivity {
        run_id: GraphRunId,
        activity_id: ActivityId,
        claimed_at: u64,
        reply: tokio::sync::oneshot::Sender<Result<TeamRunActivityStart, TeamRunActivityError>>,
    },
    AdmitActivityDispatch {
        run_id: GraphRunId,
        claim: ActivityClaim,
        request: crate::ActivityExecutionRequest,
        reply: tokio::sync::oneshot::Sender<Result<bool, StoreFault>>,
    },
    SettleActivity {
        run_id: GraphRunId,
        claim: ActivityClaim,
        outcome: ActivityExecutionOutcome,
        observed_at: u64,
        reply: tokio::sync::oneshot::Sender<Result<TeamRunActivityOutcome, TeamRunActivityError>>,
    },
    NativeRunSettled {
        file_validation: Option<(crate::run::workspace::RunFileValidationPlan, Result<(), crate::RunFileValidationError>)>,
        run_id: GraphRunId,
        delivery_id: DeliveryId,
        settled: NativeRunSettled,
        settled_at: u64,
        reply: tokio::sync::oneshot::Sender<
            Result<crate::store::NativeTerminalSettlement, StoreFault>,
        >,
    },
    TeamMessageTerminalObserved {
        identity: platform::endpoint::runtime_address::SessionIdentity,
        resolver: std::sync::Arc<dyn crate::RoleSessionIdentityResolver>,
        file_validation: Option<(crate::run::workspace::RunFileValidationPlan, Result<(), crate::RunFileValidationError>)>,
        task_observation: crate::task_execution::TaskNativeObservation,
        inspection: Option<(crate::ActivityExecutionRequest, crate::TaskNativeExecution)>,
        native_run_id: String,
        delivery_context: Option<(DeliveryId, crate::EndpointSessionId)>,
        status: organization::NativeTerminalStatus,
        assistant_texts: Result<Vec<String>, crate::application::team_message::TeamMessageFailure>,
        settled_at: u64,
        reply: tokio::sync::oneshot::Sender<Result<super::terminal_settlement::TerminalObservationOutcome, StoreFault>>,
    },
    TeamMessageRepairQueued {
        identity: platform::endpoint::runtime_address::SessionIdentity,
        requested_run_id: String,
        repair: organization::TeamMessageRepairDispatch,
        reply: tokio::sync::oneshot::Sender<()>,
    },
    TeamMessageRepairRejected {
        identity: platform::endpoint::runtime_address::SessionIdentity,
        repair: organization::TeamMessageRepairDispatch,
        reply: tokio::sync::oneshot::Sender<Result<(), StoreFault>>,
    },
    RecoverMaterializationReceipts {
        reply: tokio::sync::oneshot::Sender<super::recovery::RecoveryPlan>,
    },
    RecoverTeamReceipts {
        team_id: TeamId,
        materialization: Option<crate::TeamMaterializationRequest>,
        removal: Option<crate::TeamMaterializationRemoval>,
        guard: tokio::sync::OwnedRwLockReadGuard<()>,
        cancellation: tokio_util::sync::CancellationToken,
        reply: tokio::sync::oneshot::Sender<()>,
    },
    RecoverRoleSessions {
        native_slot: tokio::sync::OwnedSemaphorePermit,
        run_id: GraphRunId,
        guard: std::sync::Arc<tokio::sync::OwnedRwLockReadGuard<()>>,
        cancellation: tokio_util::sync::CancellationToken,
        reply: tokio::sync::oneshot::Sender<()>,
    },
    DrainTeamDeleteTasks {
        team_id: TeamId,
        reply: tokio::sync::oneshot::Sender<Vec<foundation::execution::OwnedTask<()>>>,
    },
}
