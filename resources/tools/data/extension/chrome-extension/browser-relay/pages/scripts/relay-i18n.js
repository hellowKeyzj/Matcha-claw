export function getRelayLanguage(language) {
  const code = String(language || chrome.i18n?.getUILanguage?.() || navigator.language || 'en')
    .toLowerCase().split(/[-_]/)[0]
  return Object.hasOwn(translations, code) ? code : 'en'
}

export function getRelayText(language) {
  return translations[getRelayLanguage(language)]
}

const params = new URLSearchParams(globalThis.location?.search)
export const pageLanguage = getRelayLanguage(params.get('lang') || params.get('language'))
export const relayText = getRelayText(pageLanguage)
if (globalThis.document) document.documentElement.lang = pageLanguage
