import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

export async function patchSource(source, revision, version) {
  const file = path.join(source, 'searx', 'valkeydb.py');
  const original = await readFile(file, 'utf8');
  const edits = [
    ['import os\nimport pwd\n', 'import getpass\n'],
    [
      '        _pw = pwd.getpwuid(os.getuid())\n        logger.exception("[%s (%s)] can\'t connect valkey DB ...", _pw.pw_name, _pw.pw_uid)',
      '        logger.exception("[%s] can\'t connect valkey DB ...", getpass.getuser())',
    ],
  ];
  let patched = original;
  for (const [before, after] of edits) {
    if (patched.split(before).length !== 2) throw new Error('SearXNG Windows patch context mismatch');
    patched = patched.replace(before, after);
  }
  patched = patched.replace('# SPDX-License-Identifier: AGPL-3.0-or-later\n', '# SPDX-License-Identifier: AGPL-3.0-or-later\n# Modified by MatchaClaw on 2026-10-18: Windows-compatible user diagnostics.\n');
  await writeFile(file, patched);
  await writeFile(path.join(source, 'searx', 'version_frozen.py'), `# SPDX-License-Identifier: AGPL-3.0-or-later
# Generated by MatchaClaw for the pinned official source archive.
VERSION_STRING = "${version}"
VERSION_TAG = "${version}"
DOCKER_TAG = "${revision}"
GIT_URL = "https://github.com/searxng/searxng"
GIT_BRANCH = "${revision}"
`);
  return [
    { file: 'searx/valkeydb.py', change: 'Replace Unix-only pwd diagnostics with getpass.getuser for Windows.' },
    { file: 'searx/version_frozen.py', change: 'Freeze version and upstream identity; never inspect the host Git working directory.' },
  ];
}
